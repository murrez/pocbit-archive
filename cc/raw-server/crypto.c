static uint8_t rotate_left_8(uint8_t value, unsigned int count)
{
    return (uint8_t)((uint8_t)(value << count) | (value >> (8u - count)));
}

static uint8_t rotate_right_8(uint8_t value, unsigned int count)
{
    return (uint8_t)((value >> count) | (uint8_t)(value << (8u - count)));
}

static uint8_t gf_multiply(uint8_t a, uint8_t b)
{
    uint8_t product = 0;

    while (b != 0u) {
        uint8_t high_bit;

        if ((b & 1u) != 0u) {
            product ^= a;
        }
        high_bit = (uint8_t)(a & 0x80u);
        a = (uint8_t)(a << 1);
        if (high_bit != 0u) {
            a ^= 0x1bu;
        }
        b >>= 1;
    }
    return product;
}

static void gf_inverse_mix_column(uint8_t *column)
{
    uint8_t a0 = column[0];
    uint8_t a1 = column[1];
    uint8_t a2 = column[2];
    uint8_t a3 = column[3];

    column[0] = (uint8_t)(gf_multiply(a0, 14u) ^ gf_multiply(a1, 11u)
        ^ gf_multiply(a2, 13u) ^ gf_multiply(a3, 9u));
    column[1] = (uint8_t)(gf_multiply(a0, 9u) ^ gf_multiply(a1, 14u)
        ^ gf_multiply(a2, 11u) ^ gf_multiply(a3, 13u));
    column[2] = (uint8_t)(gf_multiply(a0, 13u) ^ gf_multiply(a1, 9u)
        ^ gf_multiply(a2, 14u) ^ gf_multiply(a3, 11u));
    column[3] = (uint8_t)(gf_multiply(a0, 11u) ^ gf_multiply(a1, 13u)
        ^ gf_multiply(a2, 9u) ^ gf_multiply(a3, 14u));
}

int config_crypt_buffer(char *data, int32_t length)
{
    uint8_t key_schedule[128] = {0};
    uint8_t state_a[256];
    uint8_t state_b[256];
    uint8_t state_c[256];
    uint8_t random_a;
    uint8_t random_b;
    uint8_t salt;
    uint32_t position = 0;
    uint32_t i = 0;
    uint32_t j = 0;
    int32_t mix_counter = 0;
    int32_t result;
    int32_t index;

    memcpy(key_schedule, config_key_material, sizeof(config_key_material));

    for (index = 0; index < 256; ++index) {
        state_a[index] = (uint8_t)index;
        state_b[index] = (uint8_t)index;
        state_c[index] = (uint8_t)index;
    }

    j = 0;
    for (index = 0; index < 256; ++index) {
        j = (j + state_a[index] + key_schedule[index & 0x7f]) & 0xffu;

        state_a[index] ^= state_a[j];
        state_a[j] ^= state_a[index];
        state_a[index] ^= state_a[j];
    }

    j = 0;
    for (index = 0; index < 256; ++index) {
        j = (j + state_b[index] + config_table_18fe4[index & 0xff]) & 0xffu;
        state_b[index] ^= state_b[j];
        state_b[j] ^= state_b[index];
        state_b[index] ^= state_b[j];
    }

    j = 0;
    for (index = 0; index < 256; ++index) {
        j = (j + state_c[index] + config_table_190e4[index & 0xff]) & 0xffu;
        state_c[index] ^= state_c[j];
        state_c[j] ^= state_c[index];
        state_c[index] ^= state_c[j];
    }

    srand((unsigned int)((uint32_t)key_schedule[127]
        + (uint32_t)key_schedule[0] + (uint32_t)length));
    random_a = (uint8_t)rand();
    random_b = (uint8_t)rand();
    salt = (uint8_t)rand();
    result = (int32_t)salt;

    i = 0;
    j = 0;

    if (length > 0) {
        do {
            uint32_t sum_index;
            uint32_t product;
            uint8_t old_i_value;
            uint8_t rotated_j_value;
            uint8_t lookup;
            uint8_t random_mask;

            i = (i + 0x11u) & 0xffu;
            sum_index = (i + j) & 0xffu;
            old_i_value = state_a[i];
            j = ((uint32_t)old_i_value + j
                + ((uint32_t)random_a ^ (uint32_t)state_a[sum_index])) & 0xffu;
            product = i * j;

            state_a[i] = rotate_left_8(old_i_value, 3u);
            rotated_j_value = rotate_right_8(state_a[j], 3u);
            state_a[j] = rotated_j_value;

            lookup = state_a[((uint32_t)rotated_j_value
                + (uint32_t)state_a[i]) & 0xffu];
            random_mask = (uint8_t)((((uint32_t)rotate_left_8(lookup, 2u)
                ^ ((uint32_t)state_a[product & 0xffu] >> 2)) & 0xf0u) | 0x0fu);
            random_mask = (uint8_t)(random_mask + random_b);
            ((uint8_t *)data)[position] ^= (uint8_t)(salt ^ random_mask);

            if ((position % 3u) == 0u) {
                uint32_t swap_index = state_a[mix_counter % 256];

                state_a[swap_index] ^= state_a[i];
                state_a[i] ^= state_a[swap_index];
                state_a[swap_index] ^= state_a[i];
            }

            if ((position & 1u) == 0u) {
                int32_t offset;

                for (offset = 0; offset < 4; ++offset) {
                    gf_inverse_mix_column(&state_a[offset]);
                }
            }

            ++position;
            mix_counter = (int32_t)((uint32_t)mix_counter + 3u);
            result = (int32_t)position;
        } while (position != (uint32_t)length);
    }

    data[length] = '\0';
    return (int)result;
}

int config_encrypt_entry(int index)
{
    return config_crypt_buffer(g_config[index].data,
        (int32_t)g_config[index].length);
}

int config_decrypt_entry(int index)
{
    return config_crypt_buffer(g_config[index].data,
        (int32_t)g_config[index].length);
}
